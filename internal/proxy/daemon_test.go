// freePort returns a loopback port nothing is listening on.
func freePort(t *testing.T) int {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = ln.Close() }()
	return portOf(t, ln.Addr())
}

func portOf(t *testing.T, addr net.Addr) int {
	t.Helper()
	tcp, ok := addr.(*net.TCPAddr)
	if !ok {
		t.Fatalf("not a TCP address: %v", addr)
	}
	return tcp.Port
}

// addProject writes a minimal repo (config + state) whose `main` worktree's web
// service is answered by a backend that replies with the project name, and
// registers it.
func addProject(t *testing.T, reg *registry.Store, name string, https bool, proxyPort int) string {
	t.Helper()
	backend := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		_, _ = io.WriteString(w, name)
	}))
	t.Cleanup(backend.Close)
	backendPort := portOf(t, backend.Listener.Addr())

	repo := t.TempDir()
	toml := fmt.Sprintf(`project = %q

[proxy]
https = %t

[services.web]
command = "true"
port_range = { min = 40000, max = 40099 }
proxy_port = %d
`, name, https, proxyPort)
	if err := os.WriteFile(filepath.Join(repo, ".isola.toml"), []byte(toml), 0o600); err != nil {
		t.Fatal(err)
	}
	stateDir := filepath.Join(repo, ".isola")
	store, err := state.NewFileStore(stateDir)
	if err != nil {
		t.Fatal(err)
	}
	st := &state.State{Services: map[string]map[string]*state.ServiceState{}, PortAssignments: map[string]int{}}
	state.SetPortAssignment(st, "main", "web", backendPort)
	if err := store.Save(st); err != nil {
		t.Fatal(err)
	}
	if err := reg.Register(registry.Project{Name: name, StateDir: stateDir, ProxyPorts: []int{proxyPort}, HTTPS: https}); err != nil {
		t.Fatal(err)
	}
	return stateDir
}

// loopbackClient dials 127.0.0.1 for any *.localhost host, as a browser does.
func loopbackClient() *http.Client {
	dialer := &net.Dialer{Timeout: 2 * time.Second}
	return &http.Client{
		Timeout: 5 * time.Second,
		Transport: &http.Transport{
			DialContext: func(ctx context.Context, network, addr string) (net.Conn, error) {
				_, port, _ := net.SplitHostPort(addr)
				return dialer.DialContext(ctx, network, net.JoinHostPort("127.0.0.1", port))
			},
			TLSClientConfig: &tls.Config{InsecureSkipVerify: true}, //nolint:gosec // test CA
		},
	}
}

func get(t *testing.T, url string) string {
	t.Helper()
	resp, err := loopbackClient().Get(url)
	if err != nil {
		t.Fatalf("GET %s: %v", url, err)
	}
	defer func() { _ = resp.Body.Close() }()
	body, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("GET %s: %d %s", url, resp.StatusCode, body)
	}
	return string(body)
}

// newTestDaemon points the registry at a temp home and returns a daemon over it.
func newTestDaemon(t *testing.T) (*Daemon, *registry.Store) {
	t.Helper()
	t.Setenv("HOME", t.TempDir())
	reg, err := registry.Open()
	if err != nil {
		t.Fatal(err)
	}
	d := NewDaemon(reg)
	t.Cleanup(d.stopAll)
	return d, reg
}

func syncOrFail(t *testing.T, d *Daemon) {
	t.Helper()
	if err := d.sync(); err != nil {
		t.Fatal(err)
	}
}

func caExists(d *Daemon) bool {
	_, err := os.Stat(cert.CAPath(d.certDir))
	return err == nil
}

// TestDaemonServesBothSchemesOnSharedPort is the two-project regression: one
// project with `https = false` and one with `https = true` share a proxy port.
// The daemon used to bind the port as TLS only (the "superset"), so the HTTP
// project got "Client sent an HTTP request to an HTTPS server". Each project must
// be reachable on its own scheme, whichever registered first.
func TestDaemonServesBothSchemesOnSharedPort(t *testing.T) {
	d, reg := newTestDaemon(t)
	port := freePort(t)
	addProject(t, reg, "plain", false, port)
	addProject(t, reg, "secure", true, port)
	syncOrFail(t, d)

	// The CA must exist as soon as any project wants HTTPS, before any request,
	// so `isola up` can find it to trust.
	if !caExists(d) {
		t.Error("CA not generated by sync although a project wants https")
	}

	p := strconv.Itoa(port)
	if got := get(t, "http://main.plain.localhost:"+p+"/"); got != "plain" {
		t.Errorf("http plain project = %q", got)
	}
	if got := get(t, "https://main.secure.localhost:"+p+"/"); got != "secure" {
		t.Errorf("https secure project = %q", got)
	}
}

// TestDaemonRefusesTLSWithoutHTTPSProject: with no project wanting HTTPS, a
// stray https:// request is refused and no CA is minted.
func TestDaemonRefusesTLSWithoutHTTPSProject(t *testing.T) {
	d, reg := newTestDaemon(t)
	port := freePort(t)
	addProject(t, reg, "plain", false, port)
	syncOrFail(t, d)

	p := strconv.Itoa(port)
	if resp, err := loopbackClient().Get("https://main.plain.localhost:" + p + "/"); err == nil {
		_ = resp.Body.Close()
		t.Error("https request succeeded with no project wanting https")
	}
	if caExists(d) {
		t.Error("CA generated although no project wants https")
	}
	if got := get(t, "http://main.plain.localhost:"+p+"/"); got != "plain" {
		t.Errorf("http after refused handshake = %q", got)
	}
}

// TestDaemonPicksUpHTTPSWithoutRestart: turning on https for a project whose port
// is already served takes effect on the next sync, with no daemon restart.
func TestDaemonPicksUpHTTPSWithoutRestart(t *testing.T) {
	d, reg := newTestDaemon(t)
	port := freePort(t)
	stateDir := addProject(t, reg, "app", false, port)
	syncOrFail(t, d)

	if err := reg.Register(registry.Project{Name: "app", StateDir: stateDir, ProxyPorts: []int{port}, HTTPS: true}); err != nil {
		t.Fatal(err)
	}
	syncOrFail(t, d)

	if got := get(t, "https://main.app.localhost:"+strconv.Itoa(port)+"/"); got != "app" {
		t.Errorf("https after enabling = %q", got)
	}
}

// TestDaemonReleasesUnregisteredPort: moving a project's proxy_port frees the old
// port on the next sync, so another server can bind it.
func TestDaemonReleasesUnregisteredPort(t *testing.T) {
	d, reg := newTestDaemon(t)
	oldPort, newPort := freePort(t), freePort(t)
	stateDir := addProject(t, reg, "app", false, oldPort)
	syncOrFail(t, d)

	if err := reg.Register(registry.Project{Name: "app", StateDir: stateDir, ProxyPorts: []int{newPort}}); err != nil {
		t.Fatal(err)
	}
	syncOrFail(t, d)

	addr := net.JoinHostPort("127.0.0.1", strconv.Itoa(oldPort))
	deadline := time.Now().Add(3 * time.Second)
	for {
		ln, err := net.Listen("tcp", addr)
		if err == nil {
			_ = ln.Close()
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("old port %d still held after the project moved: %v", oldPort, err)
		}
		time.Sleep(20 * time.Millisecond)
	}
	d.mu.Lock()
	_, served := d.servers[newPort]
	d.mu.Unlock()
	if !served {
		t.Errorf("new port %d not served", newPort)
	}
}

// TestDaemonRoutesMovedProxyPortWithoutRestart: after a project moves its
// proxy_port and re-registers, requests on the new port reach its service. The
// daemon used to keep the config it first loaded, so the new port 404ed until a
// restart.
func TestDaemonRoutesMovedProxyPortWithoutRestart(t *testing.T) {
	d, reg := newTestDaemon(t)
	oldPort, newPort := freePort(t), freePort(t)
	stateDir := addProject(t, reg, "app", false, oldPort)
	syncOrFail(t, d)
	if got := get(t, "http://main.app.localhost:"+strconv.Itoa(oldPort)+"/"); got != "app" {
		t.Fatalf("before move = %q", got)
	}

	cfgPath := filepath.Join(filepath.Dir(stateDir), ".isola.toml")
	b, err := os.ReadFile(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	moved := strings.Replace(string(b), "proxy_port = "+strconv.Itoa(oldPort), "proxy_port = "+strconv.Itoa(newPort), 1)
	if err := os.WriteFile(cfgPath, []byte(moved), 0o600); err != nil {
		t.Fatal(err)
	}
	// Same-length ports leave the size unchanged; make sure the mtime moves.
	future := time.Now().Add(time.Minute)
	if err := os.Chtimes(cfgPath, future, future); err != nil {
		t.Fatal(err)
	}
	if err := reg.Register(registry.Project{Name: "app", StateDir: stateDir, ProxyPorts: []int{newPort}}); err != nil {
		t.Fatal(err)
	}
	syncOrFail(t, d)

	if got := get(t, "http://main.app.localhost:"+strconv.Itoa(newPort)+"/"); got != "app" {
		t.Errorf("after move = %q", got)
	}
}

// serveDual runs an http.Server on a dualListener over ln and returns its URL
// host. The handler reports whether the request arrived over TLS.
func serveDual(t *testing.T, ln net.Listener, tlsConfig *tls.Config) *dualListener {
	t.Helper()
	dl := newDualListener(ln, tlsConfig)
	srv := &http.Server{Handler: http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		_, _ = fmt.Fprintf(w, "tls=%t", r.TLS != nil)
	})}
	go func() { _ = srv.Serve(dl) }()
	t.Cleanup(func() { _ = srv.Close() })
	return dl
}

func listenLoopback(t *testing.T) net.Listener {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	return ln
}

// TestDualListenerSetsRequestTLS: a TLS connection reaches the handler as a real
// *tls.Conn, so Request.TLS is set as behind a plain tls.Listener.
func TestDualListenerSetsRequestTLS(t *testing.T) {
	d, _ := newTestDaemon(t)
	getCert, err := d.certGetter()
	if err != nil {
		t.Fatal(err)
	}
	ln := listenLoopback(t)
	serveDual(t, ln, &tls.Config{GetCertificate: getCert})

	host := ln.Addr().String()
	if got := get(t, "https://"+host+"/"); got != "tls=true" {
		t.Errorf("https = %q, want tls=true", got)
	}
	if got := get(t, "http://"+host+"/"); got != "tls=false" {
		t.Errorf("http = %q, want tls=false", got)
	}
}

// TestDualListenerSilentClientDoesNotBlock: classification waits for a
// connection's first byte, which must not hold up other connections.
func TestDualListenerSilentClientDoesNotBlock(t *testing.T) {
	ln := listenLoopback(t)
	serveDual(t, ln, &tls.Config{})

	silent, err := net.Dial("tcp", ln.Addr().String())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = silent.Close() })

	if got := get(t, "http://"+ln.Addr().String()+"/"); got != "tls=false" {
		t.Errorf("request behind a silent connection = %q", got)
	}
}

// TestDualListenerCloseClosesPendingConns: a connection still waiting for its
// first byte is closed with the listener, not left open until sniffTimeout.
func TestDualListenerCloseClosesPendingConns(t *testing.T) {
	ln := listenLoopback(t)
	dl := newDualListener(ln, &tls.Config{})

	silent, err := net.Dial("tcp", ln.Addr().String())
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = silent.Close() }()
	// Wait until the accept loop is tracking it.
	for deadline := time.Now().Add(2 * time.Second); ; {
		dl.mu.Lock()
		n := len(dl.pending)
		dl.mu.Unlock()
		if n == 1 {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("connection never reached classification")
		}
		time.Sleep(5 * time.Millisecond)
	}

	_ = dl.Close()
	_ = silent.SetReadDeadline(time.Now().Add(2 * time.Second))
	if _, err := silent.Read(make([]byte, 1)); err == nil || isTimeout(err) {
		t.Errorf("pending connection still open after Close (read err %v)", err)
	}
	if _, err := dl.Accept(); !errors.Is(err, net.ErrClosed) {
		t.Errorf("Accept after Close = %v, want net.ErrClosed", err)
	}
}

func isTimeout(err error) bool {
	var ne net.Error
	return errors.As(err, &ne) && ne.Timeout()
}

// tempErr is an Accept error that may clear, like EMFILE.
type tempErr struct{}

func (tempErr) Error() string   { return "too many open files" }
func (tempErr) Temporary() bool { return true }
func (tempErr) Timeout() bool   { return false }

// flakyListener fails its first Accepts with a temporary error.
type flakyListener struct {
	net.Listener
	failures atomic.Int32
}

func (f *flakyListener) Accept() (net.Conn, error) {
	if f.failures.Add(-1) >= 0 {
		return nil, tempErr{}
	}
	return f.Listener.Accept()
}

// TestDualListenerRecoversFromTemporaryAcceptError: running out of file
// descriptors briefly must not take the port down for good.
func TestDualListenerRecoversFromTemporaryAcceptError(t *testing.T) {
	ln := &flakyListener{Listener: listenLoopback(t)}
	ln.failures.Store(3)
	serveDual(t, ln, &tls.Config{})

	if got := get(t, "http://"+ln.Addr().String()+"/"); got != "tls=false" {
		t.Errorf("after temporary accept errors = %q", got)
	}
}
